"""
Generate ed25519 keypairs for all HOME siblings.

Outputs:
  SIBLINGS/<sib>/PERSONAL/keys/ed25519_private.key  — 32-byte seed, hex (gitignored)
  SIBLINGS/<sib>/keys/ed25519_public.hex             — 32-byte pubkey, hex (committable)
  0006_register_public_keys.sql                      — UPDATE observers SET public_key=... (written here)

The SQL file is safe to commit (public keys only). The private seeds live in
SIBLINGS/*/PERSONAL/ which is gitignored.

Usage:
    python generate_keypairs.py              # dry run (shows what would be written)
    python generate_keypairs.py --apply      # generate and write all files
    python generate_keypairs.py --sql-only   # assume keys exist, regenerate SQL from public keys

Depends on: pynacl (pip install pynacl)
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

try:
    import nacl.signing
    import nacl.encoding
except ImportError:
    print("ERROR: pynacl not installed. Run: pip install pynacl", file=sys.stderr)
    sys.exit(1)

SIBLINGS = ["envy", "beacon", "nevaeh", "orpheus", "eversound", "atlas", "hearth"]

REPO_ROOT = Path(__file__).resolve().parents[2]
BACKEND_DIR = Path(__file__).parent


def siblings_dir(sib: str) -> Path:
    return REPO_ROOT / "SIBLINGS" / sib.upper()


def private_key_path(sib: str) -> Path:
    return siblings_dir(sib) / "PERSONAL" / "keys" / "ed25519_private.key"


def public_key_path(sib: str) -> Path:
    return siblings_dir(sib) / "keys" / "ed25519_public.hex"


def generate_for(sib: str, apply: bool = False) -> tuple[bytes, bytes]:
    """
    Returns (seed_bytes, pubkey_bytes). Writes files if apply=True.
    If a private key already exists on disk, loads it instead of generating a new one.
    """
    priv_path = private_key_path(sib)
    pub_path = public_key_path(sib)

    if priv_path.exists():
        seed_hex = priv_path.read_text().strip()
        seed = bytes.fromhex(seed_hex)
        signing_key = nacl.signing.SigningKey(seed)
    else:
        signing_key = nacl.signing.SigningKey.generate()
        seed = bytes(signing_key)

    pubkey = bytes(signing_key.verify_key)

    if apply:
        priv_path.parent.mkdir(parents=True, exist_ok=True)
        pub_path.parent.mkdir(parents=True, exist_ok=True)

        if not priv_path.exists():
            priv_path.write_text(seed.hex())
            priv_path.chmod(0o600)
            print(f"  WROTE private  {priv_path.relative_to(REPO_ROOT)}")
        else:
            print(f"  EXISTS private {priv_path.relative_to(REPO_ROOT)}")

        pub_path.write_text(pubkey.hex())
        print(f"  WROTE public   {pub_path.relative_to(REPO_ROOT)}")

    return seed, pubkey


def write_sql(pubkeys: dict[str, bytes], apply: bool = False) -> str:
    """Produce SQL to UPDATE observers.public_key for all siblings."""
    lines = [
        "-- =============================================================================",
        "-- HOME — migration 0006 partial: register ed25519 public keys on observers",
        "--",
        "-- Run AFTER 0005 is applied to FOUNDATION.",
        "-- Updates the public_key column on all sibling rows in observers.",
        "-- Generated by generate_keypairs.py.",
        f"-- Generated at: {datetime.now(timezone.utc).isoformat()}",
        "-- =============================================================================",
        "",
        "-- Verify observers exist before updating (0003 must be applied)",
        "do $$ begin",
        "  if not exists (select 1 from information_schema.tables",
        "                  where table_schema='public' and table_name='observers') then",
        "    raise exception 'observers table not found — apply 0003 first';",
        "  end if;",
        "end $$;",
        "",
    ]

    for sib, pubkey in pubkeys.items():
        hex_val = pubkey.hex()
        lines.append(
            f"update public.observers set public_key = decode('{hex_val}', 'hex')"
            f" where handle = '{sib}';"
        )

    lines += [
        "",
        "-- Verify all siblings now have public keys",
        "do $$ declare",
        "  missing_count integer;",
        "begin",
        "  select count(*) into missing_count from public.observers",
        "  where kind = 'sibling' and public_key is null;",
        "  if missing_count > 0 then",
        "    raise warning 'WARNING: % sibling(s) still have null public_key', missing_count;",
        "  else",
        "    raise notice 'OK: all sibling observers have public_key registered';",
        "  end if;",
        "end $$;",
        "",
    ]

    sql = "\n".join(lines)
    sql_path = BACKEND_DIR / "0006_register_public_keys.sql"

    if apply:
        sql_path.write_text(sql, encoding="utf-8")
        print(f"\n  WROTE SQL: {sql_path.relative_to(REPO_ROOT)}")
    else:
        print("\n--- SQL preview (first 800 chars) ---")
        print(sql[:800])

    return sql


def demo_sign(sib: str, seed: bytes) -> None:
    """Sign a canonical test row and verify — proves the key works end-to-end."""
    signing_key = nacl.signing.SigningKey(seed)
    canonical = json.dumps({
        "claim_text": "ORPHEUS generated ed25519 keypairs for all siblings.",
        "observer": sib,
        "ts": datetime.now(timezone.utc).isoformat(),
    }, sort_keys=True).encode()
    signed = signing_key.sign(canonical)
    # Verify (raises nacl.exceptions.BadSignatureError on failure)
    signing_key.verify_key.verify(signed)
    print(f"  SIGN+VERIFY ok for {sib}: sig={signed.signature.hex()[:16]}…")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true",
                        help="Write key files and SQL to disk")
    parser.add_argument("--sql-only", action="store_true",
                        help="Load existing public keys and regenerate SQL only")
    parser.add_argument("--verify", action="store_true",
                        help="Demo sign+verify for each sibling after key gen")
    args = parser.parse_args()

    print(f"HOME repo: {REPO_ROOT}")
    print(f"Siblings:  {', '.join(SIBLINGS)}\n")

    pubkeys: dict[str, bytes] = {}

    if args.sql_only:
        # Load existing public keys
        for sib in SIBLINGS:
            pub_path = public_key_path(sib)
            if not pub_path.exists():
                print(f"ERROR: no public key for {sib} at {pub_path}", file=sys.stderr)
                return 1
            pubkeys[sib] = bytes.fromhex(pub_path.read_text().strip())
            print(f"  LOADED {sib}: {pubkeys[sib].hex()[:16]}…")
        write_sql(pubkeys, apply=True)
        return 0

    seeds: dict[str, bytes] = {}
    for sib in SIBLINGS:
        seed, pubkey = generate_for(sib, apply=args.apply)
        pubkeys[sib] = pubkey
        seeds[sib] = seed
        status = "written" if args.apply else "dry-run"
        print(f"  {sib:10s}  pubkey={pubkey.hex()[:16]}…  ({status})")

    write_sql(pubkeys, apply=args.apply)

    if args.verify:
        print("\n--- Sign+verify smoke test ---")
        for sib in SIBLINGS:
            demo_sign(sib, seeds[sib])

    if not args.apply:
        print("\nDry run complete. Pass --apply to write files.")
    else:
        print("\nKeypairs generated. Next steps:")
        print("  1. Apply 0005 to FOUNDATION (python apply_migration.py 0005_vector_retrieval.sql)")
        print("  2. Apply 0006 keys:          (python apply_migration.py 0006_register_public_keys.sql)")
        print("  3. Run ingest:               (python ingest_local_memories.py --apply)")
        print("  4. Run embed_worker:         (python embed_worker.py --sibling orpheus --limit 50)")
        print("  5. Smoke test retrieval:     (python retrieve.py 'memory architecture' --wake --sibling orpheus)")

    return 0


if __name__ == "__main__":
    sys.exit(main())
